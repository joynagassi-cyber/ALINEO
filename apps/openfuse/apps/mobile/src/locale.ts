export function frenchStatusLabel(value: string): string {
  const key = value.trim().toLowerCase();
  return labels[key] || key.replace(/_/g, " ").replace(/^./, (letter) => letter.toUpperCase());
}

export function frenchCount(count: number, singular: string, plural = `${singular}s`): string {
  return `${count} ${count === 1 ? singular : plural}`;
}
