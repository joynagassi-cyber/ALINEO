function ServerToolCard({
  name,
  result,
  loading,
}: {
  name: string;
  result: unknown;
  loading: boolean;
}) {
  const { data } = useAgentWorkspace();
  const { navigate } = useWorkspace();
  let value = result;
  if (typeof value === "string") {
    try {
      value = JSON.parse(value);
    } catch {
      value = undefined;
    }
  }
  const parsed = z
    .object({
      id: z.string().optional(),
      taskId: z.string().optional(),
      error: z.string().optional(),
    })
    .safeParse(value);
  const task = parsed.success
    ? data?.tasks.find((item) => item.id === parsed.data.id || item.id === parsed.data.taskId)
    : undefined;
  const toolLabel: Record<string, string> = {
    Task: "Tâche",
    "Agent progress": "Avancement de l’assistant",
    Goal: "Objectif",
    Tracking: "Suivi",
    Memory: "Mémoire",
  };
  const translatedName = toolLabel[name] || name;
  if (task) return <TaskThreadCard task={task} />;
  return (
    <Card style={{ padding: 16, gap: 10 }}>
      <Text style={s.heading}>
        {loading ? `Enregistrement : ${translatedName.toLowerCase()}…` : translatedName}
      </Text>
      {parsed.success && parsed.data.error ? (
        <ErrorNotice error={parsed.data.error} />
      ) : (
        <Text style={s.muted}>
          {loading
            ? "En attente du serveur."
            : "Ouvrez l’espace pour consulter le résultat enregistré."}
        </Text>
      )}
      <Button
        small
        onPress={() =>
          navigate(
            name === "Goal" || name === "Tracking"
              ? "goals"
              : name === "Memory"
                ? "apps"
                : "activity",
          )
        }
      >
        Voir {translatedName.toLowerCase()}
      </Button>
    </Card>
  );
}
export function ChatScreen({
  prompt,
  thread,
  active = true,
  onReplyingChange,
}: {
  prompt?: { id: number; text: string };
  thread?: Selection;
  active?: boolean;
  onReplyingChange?: (replying: boolean) => void;
}) {
  const { api, workspace: w, refresh, navigate } = useWorkspace();
  const { data: agentWorkspace, refresh: refreshAgent } = useAgentWorkspace();
  const { enabled: richThreads, mainId, claimPrompt, refreshLocalThreads } = useFuseThread();
  const selection = thread || { id: "local", existing: true };
  const threadId = richThreads
    ? selection.id
    : selection.id === "local"
      ? "local-main"
      : selection.id;
  const agentId = `alineo-${threadId}`;
  const { agent, isReady } = useAgent({ agentId, runtimeAgentId: "default", threadId });
  const { copilotkit } = useCopilotKit();
  const renderToolCall = useRenderToolCall();
  const [draft, setDraft] = useState("");
  const [focused, setFocused] = useState(false);
  const [inputHeight, setInputHeight] = useState(44);
  const [showResults, setShowResults] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [loaded, setLoaded] = useState(false);
  // Replayed messages show before connectAgent returns; new turns wait until it does.
  const [syncing, setSyncing] = useState(false);
  const [picking, setPicking] = useState(false);
  const [attachments, setAttachments] = useState<string[]>([]);
  const list = useRef<ScrollView>(null);
  const [queue] = useState(() => new ConversationQueue());
  const choiceCompletions = useRef(
    new Map<string, { resolve: () => void; reject: (error: unknown) => void }>(),
  );
  const outbox = useSyncExternalStore(queue.subscribe, queue.getSnapshot, queue.getSnapshot);
  const followLatest = useRef(true);
  const [awayFromLatest, setAwayFromLatest] = useState(false);
  const runLock = useRef(false);
  const [saveError, setSaveError] = useState("");
  const [historyError, setHistoryError] = useState("");
  const [historyAttempt, setHistoryAttempt] = useState(0);
  // Loads still replaying history. A count, so an old load finishing does not end a newer one.
  const replaying = useRef(0);
  // Set while a queued message is being sent, so a lock refusal holds it instead of failing.
  const queuedTurn = useRef(false);
  const [keyboardPadding, setKeyboardPadding] = useState(0);

  useEffect(() => {
    if (Platform.OS !== "android") return;
    const onShow = (e: { endCoordinates: { height: number } }) => {
      const bottomNavHeight = 74;
      setKeyboardPadding(Math.max(0, e.endCoordinates.height - bottomNavHeight));
    };
    const onHide = () => setKeyboardPadding(0);
    const showSub = Keyboard.addListener("keyboardDidShow", onShow);
    const hideSub = Keyboard.addListener("keyboardDidHide", onHide);
    return () => {
      showSub.remove();
      hideSub.remove();
    };
  }, []);
  useEffect(() => {
    if (!isReady) return;
    let active = true;
    setHistoryError("");
    setLoaded(false);
    setSyncing(false);
    const replay = agent.subscribe({
      onMessagesChanged: ({ messages }) => {
        if (active && richThreads && messages.length) setLoaded(true);
      },
    });
    async function hydrate() {
      try {
        if (richThreads) {
          if (selection.existing) {
            // Replaying history re-emits past RUN_ERROR events; only connection failures block loading.
            // connectAgent returns once the thread is idle, so it also waits for a reply still
            // running from before a reload. Sending earlier fails with a thread lock.
            replaying.current += 1;
            setSyncing(true);
            try {
              await runConversationTurn(
                agentId,
                () => copilotkit.connectAgent({ agent }),
                (onError) => copilotkit.subscribe({ onError }),
                [replayedRunError],
              );
            } finally {
              replaying.current -= 1;
              if (active) setSyncing(false);
            }
          }
        } else {
          const path =
            selection.id === "local"
              ? "/api/conversation"
              : `/api/conversations/${encodeURIComponent(selection.id)}`;
          const { messages } = await api.request<{ messages: Message[] }>(path);
          if (active) agent.setMessages(messages);
        }
        if (active) setLoaded(true);
      } catch (e) {
        if (active) {
          setLoaded(false);
          setHistoryError(
            `Impossible de charger la conversation. Vos messages enregistrés n’ont pas été modifiés. ${e instanceof Error ? e.message : String(e)}`,
          );
        }
      }
    }
    void hydrate();
    return () => {
      active = false;
      replay.unsubscribe();
      if (richThreads) void agent.detachActiveRun().catch(() => {});
    };
  }, [
    agent,
    agentId,
    api,
    copilotkit,
    isReady,
    historyAttempt,
    richThreads,
    selection.id,
    selection.existing,
  ]);
  const saveHistory = useCallback(async () => {
    if (!richThreads) {
      if (selection.id === "local") {
        await api.request("/api/conversation", { messages: agent.messages }, "PUT");
      } else {
        await api.request(
          `/api/conversations/${encodeURIComponent(selection.id)}`,
          { messages: agent.messages },
          "PUT",
        );
        await refreshLocalThreads().catch(() => {});
      }
    }
    setSaveError("");
  }, [agent, api, refreshLocalThreads, richThreads, selection.id]);
  /** Runs one turn; "held" means a queued message was refused by a lock and put back on hold. */
  const run = useCallback(
    async (message?: QueuedMessage): Promise<"held" | undefined> => {
      if (runLock.current || agent.isRunning || !isReady || !loaded || syncing)
        throw new Error("La conversation n’est pas encore prête.");
      runLock.current = true;
      queuedTurn.current = Boolean(message);
      setBusy(true);
      setError("");
      if (message) agent.addMessage({ id: message.id, role: "user", content: message.text });
      try {
        await runConversationTurn(
          agentId,
          () => copilotkit.runAgent({ agent }),
          (onError) => copilotkit.subscribe({ onError }),
        );
        await Promise.all([refresh(), refreshAgent()]);
      } catch (e) {
        if (message && e instanceof ConversationTurnError && e.code === threadLocked) {
          // The server refused the turn before running it (another reply holds the thread),
          // so keep the message unsent and on hold instead of reporting a failed turn.
          agent.setMessages(agent.messages.filter((m) => m.id !== message.id));
          queue.restore(message);
          queue.pause();
          return "held";
        }
        throw e;
      } finally {
        queuedTurn.current = false;
        try {
          await saveHistory();
        } catch (e) {
          queue.pause();
          setSaveError(
            `Conversation could not be saved: ${e instanceof Error ? e.message : String(e)}`,
          );
        } finally {
          runLock.current = false;
          setBusy(false);
        }
      }
    },
    [
      agent,
      agentId,
      copilotkit,
      isReady,
      loaded,
      syncing,
      refresh,
      refreshAgent,
      saveHistory,
      queue,
    ],
  );
  const runQueued = useCallback(
    async (message: QueuedMessage) => {
      let held = false;
      try {
        held = (await run(message)) === "held";
        if (!held) choiceCompletions.current.get(message.id)?.resolve();
      } catch (error) {
        choiceCompletions.current.get(message.id)?.reject(error);
        throw error;
      } finally {
        // A held message is sent again later; its choice settles then.
        if (!held) choiceCompletions.current.delete(message.id);
      }
    },
    [run],
  );
  const flush = useCallback(() => {
    if (!loaded || syncing || !isReady || runLock.current || agent.isRunning) return;
    void queue.flush(runQueued).catch((e) => setError(e instanceof Error ? e.message : String(e)));
  }, [agent, isReady, loaded, syncing, queue, runQueued]);
  const enqueue = useCallback(
    (text: string) => {
      queue.enqueue({ id: `user-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`, text });
      followLatest.current = true;
      setAwayFromLatest(false);
      flush();
    },
    [queue, flush],
  );
  const sendChoice = useCallback(
    (text: string, retry = false): Promise<void> => {
      const snapshot = queue.getSnapshot();
      if (!loaded || !isReady || saveError || (!retry && snapshot.paused))
        return Promise.reject(new Error("La conversation ne peut pas encore recevoir de choix."));
      if (retry) {
        if (runLock.current || agent.isRunning || snapshot.running || snapshot.pending.length)
          return Promise.reject(
            new Error("Attendez la fin de la réponse en cours avant de réessayer."),
          );
        if (snapshot.paused) queue.resume();
      }
      const id = `choice-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
      const completion = new Promise<void>((resolve, reject) => {
        choiceCompletions.current.set(id, { resolve, reject });
      });
      queue.enqueue({ id, text });
      followLatest.current = true;
      setAwayFromLatest(false);
      flush();
      return completion;
    },
    [agent.isRunning, flush, isReady, loaded, queue, saveError],
  );
  useEffect(() => {
    if (!busy && !agent.isRunning && outbox.pending.length) flush();
  }, [busy, agent.isRunning, outbox.pending.length, flush]);
  useEffect(() => {
    if (active && prompt && isReady && loaded && claimPrompt(prompt.id) && prompt.text.trim())
      enqueue(prompt.text);
  }, [active, prompt, isReady, loaded, enqueue, claimPrompt]);
  useEffect(() => {
    const subscription = copilotkit.subscribe({
      onError: (event) => {
        if (event.context?.agentId && event.context.agentId !== agentId) return;
        const during = { replaying: replaying.current > 0, queuedTurn: queuedTurn.current };
        if (!showsRunError(event, during)) return;
        const failure = event.error instanceof Error ? event.error : new Error(String(event.error));
        setError(failure.message);
      },
    });
    return () => subscription.unsubscribe();
  }, [copilotkit, agentId, queue]);
  async function stop() {
    queue.pause();
    try {
      await copilotkit.stopAgent({ agent });
    } catch (e) {
      setError(`Impossible d’arrêter la réponse : ${e instanceof Error ? e.message : String(e)}`);
    }
  }
  function send() {
    const text = draft.trim();
    if (!text || !isReady || !loaded) return;
    // A new submission can continue after Stop; held follow-ups still need explicit resume.
    if (!busy && !agent.isRunning && !saveError && !queue.getSnapshot().pending.length)
      queue.resume();
    setShowResults(false);
    const files = w.files.filter((f) => attachments.includes(f.id));
    enqueue(
      text +
        (files.length
          ? `\n\nAttached documents: ${files.map((f) => `${f.name} (artifact ID: ${f.id})`).join(", ")}`
          : ""),
    );
    setDraft("");
    setInputHeight(44);
    setAttachments([]);
    setPicking(false);
  }
  const messages = agent.messages || [];
  const latestPanelId = latestJevPanelId(messages, threadId);
  const latestUserIndex = messages.reduce(
    (last, message, index) => (message.role === "user" ? index : last),
    -1,
  );
  const latestUserText =
    latestUserIndex >= 0 && typeof messages[latestUserIndex]?.content === "string"
      ? messages[latestUserIndex].content
      : null;
  const visible = messages.filter((m) => m.role === "user" || m.role === "assistant");
  const latestDesktop = messages
    .flatMap((m) => ("toolCalls" in m ? m.toolCalls || [] : []))
    .filter((call) => call.function.name === "use_desktop")
    .at(-1)?.id;
  const replying = busy || agent.isRunning;
  useEffect(() => {
    if (!active) return;
    onReplyingChange?.(replying);
    return () => onReplyingChange?.(false);
  }, [active, onReplyingChange, replying]);

  return (
    <View style={{ flex: 1 }}>
      <ScrollView
        ref={list}
        showsVerticalScrollIndicator={false}
        contentContainerStyle={{ gap: 13, paddingTop: 15, paddingBottom: 20, flexGrow: 1 }}
        onScroll={({ nativeEvent: { contentOffset, contentSize, layoutMeasurement } }) => {
          const nearEnd = contentSize.height - contentOffset.y - layoutMeasurement.height < 100;
          followLatest.current = nearEnd;
          setAwayFromLatest(visible.length > 0 && !nearEnd);
        }}
        scrollEventThrottle={100}
        onContentSizeChange={() => {
          if (active && visible.length > 0 && followLatest.current)
            list.current?.scrollToEnd({ animated: false });
        }}
        keyboardShouldPersistTaps="handled"
      >
        {!!historyError && (
          <>
            <ErrorNotice error={historyError} />
            <Button onPress={() => setHistoryAttempt((attempt) => attempt + 1)}>
              Réessayer de charger la conversation
            </Button>
          </>
        )}
        {!visible.length ? (
          <View
            style={{
              flexGrow: 1,
              flexShrink: 0,
              justifyContent: "center",
              alignItems: "center",
              paddingVertical: 34,
              gap: 15,
            }}
          >
            {selection.id !== mainId && (
              <View style={{ marginBottom: 2 }}>
                <MicOrb size={112} appearance={agentWorkspace?.identity.micOrb} />
              </View>
            )}
            <Heading
              level={2}
              style={{
                fontSize: 28,
                letterSpacing: -1,
                lineHeight: 34,
                color: colors.text,
                textAlign: "center",
                maxWidth: 380,
              }}
            >
              {selection.id !== mainId
                ? "Votre prochaine avancée commence ici."
                : "Commencez par une chose."}
            </Heading>
            <Text style={[s.muted, { maxWidth: 340, textAlign: "center", lineHeight: 23 }]}>
              {selection.id !== mainId
                ? "Un objectif à la fois : choisissez une priorité, confiez une tâche à Alineo et faites avancer votre projet."
                : "Demandez de l’aide pour une tâche, ou ouvrez le courrier ou les fichiers pour choisir un élément."}
            </Text>
            <View style={{ width: "100%", maxWidth: 360, marginTop: 14, gap: 8 }}>
              {selection.id !== mainId ? (
                <>
                  <Button
                    primary
                    onPress={() =>
                      enqueue(
                        "Aide-moi à définir une prochaine étape concrète pour ce nouveau sujet.",
                      )
                    }
                  >
                    Définir ma prochaine étape
                  </Button>
                  <Button onPress={() => enqueue("Aide-moi à prioriser le travail sur ce sujet.")}>
                    Choisir une priorité
                  </Button>
                </>
              ) : (
                [
                  {
                    text: "Organiser ma journée",
                    action: () => enqueue("Aide-moi à organiser ma journée"),
                  },
                  { text: "Ouvrir le courrier", action: () => navigate("mail") },
                  { text: "Importer un PDF", action: () => navigate("files") },
                ].map((item) => (
                  <Button key={item.text} onPress={item.action}>
                    {item.text}
                  </Button>
                ))
              )}
            </View>
          </View>
        ) : (
          visible.map((message) => {
            const user = message.role === "user";
            const text =
              typeof message.content === "string"
                ? user
                  ? displayJevUserMessage(
                      message.content,
                      messages.slice(0, messages.indexOf(message)),
                    )
                  : message.content
                : "";
            const toolCalls = "toolCalls" in message ? message.toolCalls || [] : [];
            return (
              <View
                key={message.id}
                style={{
                  alignSelf: user ? "flex-end" : "flex-start",
                  maxWidth: user ? "85%" : "95%",
                  width: toolCalls.length ? "95%" : undefined,
                  gap: 8,
                }}
              >
                {!!text && (
                  <View
                    style={{
                      paddingHorizontal: 16,
                      paddingVertical: 13,
                      borderRadius: 22,
                      borderBottomRightRadius: user ? 7 : 22,
                      borderBottomLeftRadius: user ? 22 : 7,
                      backgroundColor: user ? colors.accent : colors.sky,
                    }}
                  >
                    {user ? (
                      <Text selectable style={[s.text, { fontSize: 16, lineHeight: 24 }]}>
                        {text}
                      </Text>
                    ) : (
                      <AssistantResponse content={text} />
                    )}
                  </View>
                )}
                <JevInteractionContext.Provider
                  value={{
                    threadId,
                    busy:
                      busy ||
                      agent.isRunning ||
                      !loaded ||
                      !isReady ||
                      !!outbox.pending.length ||
                      outbox.paused ||
                      !!saveError,
                    latestPanelId,
                    latestUserText,
                    send: sendChoice,
                    retry: (text) => sendChoice(text, true),
                    canRetry:
                      loaded &&
                      isReady &&
                      !busy &&
                      !agent.isRunning &&
                      !outbox.running &&
                      !outbox.pending.length &&
                      !saveError,
                    confirmedSelection: (panelId) => confirmedJevSelection(messages, panelId),
                  }}
                >
                  <BrowserRunContext
                    value={{
                      running: busy || agent.isRunning,
                      active:
                        (busy || agent.isRunning) && messages.indexOf(message) > latestUserIndex,
                    }}
                  >
                    {toolCalls.map((toolCall) => {
                      const toolMessage = messages.find(
                        (candidate): candidate is ToolMessage =>
                          candidate.role === "tool" && candidate.toolCallId === toolCall.id,
                      );
                      return (
                        <View key={toolCall.id}>{renderToolCall({ toolCall, toolMessage })}</View>
                      );
                    })}
                  </BrowserRunContext>
                </JevInteractionContext.Provider>
              </View>
            );
          })
        )}
        {!!latestDesktop && (
          <DesktopToolCard
            live
            toolCallId={latestDesktop}
            result={
              messages.find(
                (message) => message.role === "tool" && message.toolCallId === latestDesktop,
              )?.content
            }
            loading={replying}
          />
        )}
        {!richThreads && (
          <>
            {(w.files.some((file) => file.parentId) ||
              w.browsers.some((browser) => browser.status === "active") ||
              !!agentWorkspace?.artifacts.length) && (
              <Button
                small
                style={{ alignSelf: "flex-start", marginTop: 6 }}
                onPress={() => setShowResults(!showResults)}
              >
                {showResults ? "Masquer les résultats récents" : "Résultats récents"}
              </Button>
            )}
            {showResults && (
              <>
                {w.files
                  .filter((file) => file.parentId)
                  .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
                  .slice(0, 1)
                  .map((file) => (
                    <FileThreadCard key={file.id} file={file} />
                  ))}
                {w.browsers
                  .filter((browser) => browser.status === "active")
                  .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
                  .slice(0, 1)
                  .map((browser) => (
                    <BrowserThreadCard key={browser.id} browser={browser} />
                  ))}
                {[...(agentWorkspace?.artifacts || [])]
                  .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
                  .filter(
                    (artifact, index, items) =>
                      items.findIndex((item) => item.kind === artifact.kind) === index,
                  )
                  .slice(0, 2)
                  .reverse()
                  .map((artifact) => (
                    <ArtifactCard key={artifact.id} artifact={artifact} />
                  ))}
              </>
            )}
          </>
        )}
        {selection.id === mainId && <BackgroundUpdates />}
        {(busy || agent.isRunning) && (
          <View
            accessibilityLabel="Alineo travaille"
            style={[
              s.row,
              {
                alignSelf: "flex-start",
                gap: 7,
                paddingHorizontal: 19,
                paddingVertical: 18,
                backgroundColor: colors.sky,
                borderRadius: 28,
              },
            ]}
          >
            {[0.4, 0.75, 0.5].map((opacity) => (
              <View
                key={opacity}
                style={{
                  width: 8,
                  height: 8,
                  borderRadius: 4,
                  backgroundColor: colors.muted,
                  opacity,
                }}
              />
            ))}
          </View>
        )}
        <ErrorNotice error={error} />
        {!!error && (
          <Button
            style={{ alignSelf: "flex-start" }}
            icon={RotateCcw}
            disabled={busy || agent.isRunning || !loaded || syncing || !isReady}
            onPress={() => {
              void run()
                .then(() => {
                  if (!queue.getSnapshot().paused) flush();
                })
                .catch((e) => setError(e instanceof Error ? e.message : String(e)));
            }}
          >
            Réessayer la réponse
          </Button>
        )}
      </ScrollView>
      {awayFromLatest && (
        <Button
          small
          icon={ArrowDown}
          style={{ alignSelf: "center", marginBottom: 10 }}
          onPress={() => {
            followLatest.current = true;
            setAwayFromLatest(false);
            list.current?.scrollToEnd({ animated: true });
          }}
        >
          Messages les plus récents
        </Button>
      )}
      <KeyboardAvoidingView
        behavior={Platform.OS === "ios" ? "padding" : undefined}
        style={keyboardPadding > 0 ? { paddingBottom: keyboardPadding } : undefined}
      >
        <ErrorNotice error={saveError} />
        {!!saveError && (
          <Button
            small
            disabled={busy}
            onPress={() => {
              void saveHistory().catch((e) => setSaveError(String(e)));
            }}
          >
            Réessayer d’enregistrer la conversation
          </Button>
        )}
        {!!outbox.pending.length && (
          <View style={{ padding: 12, gap: 6 }}>
            <Text style={s.small}>
              {outbox.paused ? "Messages en attente" : "À suivre"} · Gardez l’application ouverte
              jusqu’à l’envoi
            </Text>
            {outbox.pending.map((message) => (
              <View key={message.id} style={[s.row, { gap: 8 }]}>
                <Text numberOfLines={2} style={[s.muted, { flex: 1 }]}>
                  {displayJevUserMessage(message.text, messages)}
                </Text>
                <Pressable
                  accessibilityRole="button"
                  accessibilityLabel={`Retirer le message en attente : ${displayJevUserMessage(message.text, messages)}`}
                  hitSlop={10}
                  onPress={() => {
                    queue.remove(message.id);
                    choiceCompletions.current
                      .get(message.id)
                      ?.reject(new Error("Le choix a été retiré de la file d’attente."));
                    choiceCompletions.current.delete(message.id);
                  }}
                  style={{ padding: 8 }}
                >
                  <X size={16} color={colors.muted} />
                </Pressable>
              </View>
            ))}
            {outbox.paused && (
              <Button
                small
                disabled={busy || !!saveError}
                onPress={() => {
                  queue.resume();
                  flush();
                }}
              >
                Envoyer les messages en attente
              </Button>
            )}
          </View>
        )}
        {picking && (
          <Card style={{ marginBottom: 12, padding: 15 }}>
            <Text style={s.heading}>Ajouter un document</Text>
            <ScrollView style={{ maxHeight: 230 }} keyboardShouldPersistTaps="handled">
              {w.files.length ? (
                w.files.map((f) => (
                  <CheckRow
                    key={f.id}
                    checked={attachments.includes(f.id)}
                    label={f.name}
                    onPress={() =>
                      setAttachments(
                        attachments.includes(f.id)
                          ? attachments.filter((id) => id !== f.id)
                          : [...attachments, f.id],
                      )
                    }
                  />
                ))
              ) : (
                <Text style={s.muted}>
                  Importez un PDF dans Fichiers pour l’utiliser dans une conversation.
                </Text>
              )}
            </ScrollView>
            <Button
              small
              onPress={() => setPicking(false)}
              style={{ alignSelf: "flex-end", marginTop: 8 }}
            >
              Terminé
            </Button>
          </Card>
        )}
        <View
          style={{
            backgroundColor: colors.card,
            borderRadius: 32,
            borderWidth: focused ? 2 : 1,
            borderColor: focused ? colors.focus : colors.line,
            padding: 8,
            shadowColor: "#000000",
            shadowOpacity: focused ? 0.1 : 0.06,
            shadowRadius: 20,
            shadowOffset: { width: 0, height: 4 },
            elevation: 4,
          }}
        >
          {attachments.length > 0 && (
            <View style={[s.row, { gap: 6, flexWrap: "wrap", padding: 9 }]}>
              {w.files
                .filter((f) => attachments.includes(f.id))
                .map((f) => (
                  <Pressable
                    key={f.id}
                    accessibilityRole="button"
                    accessibilityLabel={`Retirer la pièce jointe : ${f.name}`}
                    onPress={() => setAttachments((ids) => ids.filter((id) => id !== f.id))}
                    style={[
                      s.row,
                      {
                        gap: 7,
                        maxWidth: "100%",
                        minHeight: 44,
                        backgroundColor: colors.sky,
                        borderRadius: 22,
                        paddingHorizontal: 11,
                        paddingVertical: 8,
                      },
                    ]}
                  >
                    <FileText size={14} color={colors.accentDark} />
                    <Text
                      numberOfLines={1}
                      style={{ flexShrink: 1, fontSize: 12, color: colors.text }}
                    >
                      {f.name}
                    </Text>
                    <X size={13} color={colors.muted} />
                  </Pressable>
                ))}
            </View>
          )}
          <View style={[s.row, { gap: 7, alignItems: "flex-end" }]}>
            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Joindre un document"
              accessibilityState={{ expanded: picking }}
              onPress={() => setPicking(!picking)}
              style={({ pressed }) => ({
                width: 44,
                height: 44,
                alignItems: "center",
                justifyContent: "center",
                borderRadius: 24,
                backgroundColor: picking || pressed ? colors.sky : "transparent",
              })}
            >
              <Text style={{ color: colors.text, fontSize: 29, fontWeight: "300", lineHeight: 32 }}>
                +
              </Text>
            </Pressable>
            <Field
              bare
              label="Message à Alineo"
              labelStyle={{ fontSize: 12, lineHeight: 16, color: colors.muted }}
              containerStyle={{ flex: 1, marginBottom: 0, gap: 0 }}
              value={draft}
              onChangeText={setDraft}
              onContentSizeChange={(event) =>
                setInputHeight(Math.max(44, Math.min(140, event.nativeEvent.contentSize.height)))
              }
              placeholder={
                !isReady
                  ? "Connexion…"
                  : !loaded
                    ? historyError
                      ? "Conversation indisponible"
                      : "Chargement de la conversation…"
                    : "Écrire un message…"
              }
              placeholderTextColor={colors.muted}
              selectionColor={colors.accentDark}
              onFocus={() => setFocused(true)}
              onBlur={() => setFocused(false)}
              style={{
                flex: 1,
                color: colors.text,
                height: inputHeight,
                minHeight: 44,
                maxHeight: 140,
                fontSize: 17,
                lineHeight: 24,
                paddingHorizontal: 2,
                paddingTop: 8,
                paddingBottom: 8,
                ...noFocusRing,
              }}
              multiline
              editable
              onKeyPress={
                Platform.OS === "web"
                  ? (event) => {
                      if (
                        event.nativeEvent.key === "Enter" &&
                        !("shiftKey" in event.nativeEvent && event.nativeEvent.shiftKey)
                      ) {
                        event.preventDefault();
                        send();
                      }
                    }
                  : undefined
              }
            />
            <Pressable
              accessibilityRole="button"
              accessibilityLabel={replying ? "Arrêter la réponse" : "Envoyer le message"}
              accessibilityHint={
                replying ? "Interrompre la réponse en cours." : "Envoyer ce message à Alineo."
              }
              accessibilityState={{
                disabled: !replying && (!draft.trim() || !loaded || !isReady),
                busy: replying,
              }}
              disabled={!replying && (!draft.trim() || !loaded || !isReady)}
              onPress={replying ? () => void stop() : send}
              style={({ pressed }) => ({
                width: 44,
                height: 44,
                borderRadius: 24,
                backgroundColor: replying || draft.trim() ? colors.accent : colors.disabled,
                alignItems: "center",
                justifyContent: "center",
                transform: [{ scale: pressed ? 0.94 : 1 }],
              })}
            >
              {replying ? (
                <Square size={18} fill={colors.text} strokeWidth={0} />
              ) : (
                <ArrowUp
                  size={25}
                  strokeWidth={1.8}
                  color={draft.trim() ? colors.text : colors.muted}
                />
              )}
            </Pressable>
          </View>
        </View>
      </KeyboardAvoidingView>
    </View>
  );
}
